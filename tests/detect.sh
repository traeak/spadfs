#!/usr/bin/env bash
# Task 0.3 — structured corruption detection baseline.
#
# For each (metadata target x corruption class), corrupt a volume and record
# whether spadfsck notices.
#
# IMPORTANT: the check must be `spadfsck -n -f`. Plain `-n` short-circuits with
# "filesystem is clean, no checking needed" whenever the volume carries no
# recorded error flag, so it never traverses and reports a false clean. `-f`
# forces the full pass; `-n` keeps it read-only.
#
# Layer attribution caveat: the two columns below are NOT "checksum vs
# structural". Measured behaviour is that spadfsck validates metadata checksums
# even on a volume created with `--no-checksums`, so both columns come out the
# same. Isolating which layer catches a given class needs a different experiment:
# corrupt the payload and then RESTRIPE the checksum to match the corrupted
# bytes, so the checksum cannot fire. Any remaining detection is then purely
# structural. That refinement is tracked as follow-up work, not claimed here.
#
# Runs without root. Output is markdown; redirect to
# tests/BASELINE-checksum-detection.md.

set -uo pipefail

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"
. "$TESTS_DIR/fixtures.sh"

require_tools

SIZE="${TEST_IMAGE_SIZE:-16M}"
TARGETS=(superblock txblock apage_index cct cct_live root_fnode root_dir)
CLASSES=(bitflip byte_transpose word_swap word_dup block_copy xor_cancel zero_out)

base_for() {
	local mode="$1" img="$WORKDIR/base-$mode.img"
	if [ ! -f "$img" ]; then
		make_image "$img" "$SIZE" "--$mode" || die "base $mode failed"
		# Prime the crash-count table. On a fresh volume it is all zeros, so
		# every cct class is a no-op and the target tests nothing. Priming gives
		# it plausible post-mount contents (see tests/prime.py).
		python3 "$TESTS_DIR/prime.py" "$img" --cc 4 --base-txc 1388 \
			|| die "priming base $mode failed"
		# Priming must not itself break the volume.
		check_clean "$img" -n || die "primed base $mode is not clean"
	fi
	printf '%s' "$img"
}

# -> DETECTED | MISSED | NOOP | ERROR
run_case() {
	local mode="$1" target="$2" cls="$3"
	local img="$WORKDIR/case.img" rc=0
	cp -f "$(base_for "$mode")" "$img"

	python3 "$TESTS_DIR/corrupt.py" "$img" "$target" "$cls" >/dev/null 2>&1 || rc=$?
	if [ "$rc" -eq 3 ]; then
		printf 'NOOP'
		return 0
	elif [ "$rc" -ne 0 ]; then
		printf 'ERROR'
		return 0
	fi

	if "$FSCK" -n -f "$img" >/dev/null 2>&1; then
		printf 'MISSED'
	else
		printf 'DETECTED'
	fi
}

printf '# Checksum detection baseline\n\n'
printf 'Generated by `tests/detect.sh` against this tree. Do not hand-edit.\n\n'
printf 'Detector: `spadfsck -n -f` (forced full check, read-only).\n'
printf 'Image size: %s. Corruption is applied to the first 512-byte unit at the\n' "$SIZE"
printf 'target whose contents the class can actually change.\n\n'
printf '| Target | Class | checksums | no-checksums | Result |\n'
printf '|---|---|---|---|---|\n'

undetected=0
detected=0
noop=0
total=0

for target in "${TARGETS[@]}"; do
	for cls in "${CLASSES[@]}"; do
		ck="$(run_case checksums "$target" "$cls")"
		nc="$(run_case no-checksums "$target" "$cls")"
		total=$((total + 1))

		case "$ck" in
			DETECTED) result="detected"; detected=$((detected + 1)) ;;
			MISSED)   result="**NOT DETECTED**"; undetected=$((undetected + 1)) ;;
			NOOP)     result="n/a (no live bytes to change)"; noop=$((noop + 1)) ;;
			*)        result="harness error"; noop=$((noop + 1)) ;;
		esac

		printf '| %s | %s | %s | %s | %s |\n' \
			"$target" "$cls" "$ck" "$nc" "$result"
	done
done

printf '\n## Summary\n\n'
printf -- '- cases attempted: %d\n' "$total"
printf -- '- detected: %d\n' "$detected"
printf -- '- **NOT detected: %d**\n' "$undetected"
printf -- '- not applicable / harness error: %d\n' "$noop"
